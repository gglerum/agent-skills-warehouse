#!/usr/bin/env python3
"""Findings and user-feedback items as one file per item; the overview documents are generated from them.

Usage: python3 findings.py [--config FILE] [fb] <command> [arguments]

Records (paths come from the configuration, relative to the configuration file or the working directory):

  <findings_dir>/<ID>.md                one finding (front matter + the finding text, one line: it becomes a table cell)
  <findings_dir>/_intro.md              text above the overview (first line is its title)
  <findings_dir>/_overview.md           text below the generated count line
  <findings_dir>/_groups/NN-slug.md     one table group: front matter `title`, then text, a table header and the marker
                                        `<!-- findings-table -->`, then text after the table
  <feedback_dir>/FB-001.md              one feedback item (front matter + a section starting `### FB-001 title`)
  <feedback_dir>/_intro.md, _template.md   text around the generated table and the sections

Generated, committed, never edited by hand: `findings_index` and `feedback_index`.
Commands: add, status, show, list, counts, index, check; prefix with `fb` for feedback items (add is for findings only).
Python 3.10+ standard library only.
"""

from __future__ import annotations

import json
import os
import re
import sys
from pathlib import Path

DEFAULTS = {
    "findings_dir": "docs/findings",
    "feedback_dir": "docs/feedback",
    "findings_index": "docs/findings.md",
    "feedback_index": "docs/feedback.md",
    "feedback_prefix": "FB",
    "finding_id_pattern": "^[A-Z][0-9]+[a-z]?$",
    "decisions_link": None,  # e.g. "decisions.md": adds "Details and recommendations: [..](..)" to the overview
    "command": "python3 findings.py",
}

STATUSES = ("open", "fixed", "accepted", "wont-fix", "decided")
LABELS = {"open": "Open", "fixed": "Fixed", "accepted": "Accepted", "wont-fix": "Won't fix", "decided": "Decided"}
SEVERITIES = ("Blocker", "High", "Medium", "Low", "Info", "False positive")
F_KEYS = ("id", "group", "position", "severity", "found_by", "status", "status_note")
FB_KEYS = ("id", "area", "summary", "priority", "status", "related")
MARKER = "<!-- findings-table -->"

CFG: dict = {}
ROOT = Path.cwd()
F_DIR = FB_DIR = Path()
ID_RE = FB_ID_RE = re.compile("")


def configure(config_path: str | None) -> None:
    global CFG, ROOT, F_DIR, FB_DIR, ID_RE, FB_ID_RE
    CFG = dict(DEFAULTS)
    ROOT = Path.cwd()
    if config_path:
        path = Path(config_path).resolve()
        CFG.update(json.loads(path.read_text(encoding="utf-8")))
        ROOT = path.parent
    ROOT = Path(os.environ.get("FINDINGS_ROOT") or ROOT)
    F_DIR, FB_DIR = ROOT / CFG["findings_dir"], ROOT / CFG["feedback_dir"]
    ID_RE = re.compile(CFG["finding_id_pattern"])
    FB_ID_RE = re.compile(rf"^{re.escape(CFG['feedback_prefix'])}-[0-9]{{3}}$")


def rel(path: Path) -> str:
    try:
        return str(path.relative_to(ROOT))
    except ValueError:
        return str(path)


def generated_note(src: str) -> str:
    cmd = CFG["command"]
    return (
        f"> Generated by `{cmd} index` from the files in `{src}/`. Do not edit this file: change a record with "
        f"`{cmd}` (or edit its file) and run `{cmd} index`. On a merge conflict in this file, run "
        f"`{cmd} index` and add the result."
    )


def read_record(path: Path) -> tuple[dict, str]:
    text = path.read_text(encoding="utf-8")
    m = re.match(r"---\n(.*?)\n---\n?(.*)\Z", text, re.S)
    if not m:
        raise ValueError(f"{path}: no front matter")
    meta = {}
    for line in m.group(1).split("\n"):
        key, _, value = line.partition(": ")
        meta[key] = json.loads(value)
    return meta, m.group(2).strip("\n")


def write_record(path: Path, meta: dict, keys: tuple, body: str) -> None:
    if "severity_text" in meta:
        keys = keys + ("severity_text",)
    lines = [f"{k}: {json.dumps(meta[k], ensure_ascii=False)}" for k in keys]
    path.write_text("---\n" + "\n".join(lines) + "\n---\n" + body.strip("\n") + "\n", encoding="utf-8")


def findings() -> list[tuple[dict, str]]:
    return [read_record(p) for p in sorted(F_DIR.glob("*.md")) if not p.name.startswith("_")]


def feedback_items() -> list[tuple[dict, str]]:
    return [read_record(p) for p in sorted(FB_DIR.glob("*.md")) if not p.name.startswith("_")]


def groups() -> list[tuple[str, str]]:
    result = []
    for p in sorted((F_DIR / "_groups").glob("*.md")):
        meta, body = read_record(p)
        result.append((meta["title"], body))
    return result


def render_row(meta: dict, text: str) -> str:
    default = f"**{meta['severity']}**" if meta["severity"] == "Blocker" else meta["severity"]
    severity = meta.get("severity_text", default)
    status = LABELS[meta["status"]] + meta["status_note"]
    return f"| {meta['id']} | {severity} | {text} | {meta['found_by']} | {status} |"


def counts(items: list[tuple[dict, str]]) -> dict:
    result = {s: 0 for s in STATUSES}
    for meta, _ in items:
        result[meta["status"]] += 1
    return result


def counts_text(c: dict) -> str:
    return f"{c['fixed']} fixed, {c['accepted'] + c['wont-fix']} accepted or won't fix, {c['open']} open, {c['decided']} decided (to build, tracked elsewhere)"


def order(items: list[tuple[dict, str]]) -> list[tuple[dict, str]]:
    titles = [t for t, _ in groups()]
    return sorted(items, key=lambda it: (titles.index(it[0]["group"]) if it[0]["group"] in titles else len(titles), it[0]["position"]))


def ids_with(items: list[tuple[dict, str]], status: str) -> list[str]:
    return [m["id"] for m, _ in order(items) if m["status"] == status]


def intro_of(directory: Path, default: str) -> tuple[str, str]:
    path = directory / "_intro.md"
    text = path.read_text(encoding="utf-8").strip("\n") if path.exists() else default
    title, _, rest = text.partition("\n")
    return title, rest.strip("\n")


def optional(path: Path) -> str:
    return path.read_text(encoding="utf-8").strip("\n") if path.exists() else ""


def generate_findings() -> str:
    items = findings()
    title, rest = intro_of(F_DIR, "# Findings")
    parts = [title + "\n\n" + generated_note(CFG["findings_dir"]) + ("\n\n" + rest if rest else "")]
    overview = f"{len(items)} findings: {counts_text(counts(items))}."
    open_ids = ids_with(items, "open")
    if open_ids:
        overview += " Open: " + ", ".join(open_ids) + "."
    if CFG["decisions_link"]:
        overview += f" Details and recommendations: [{CFG['decisions_link']}]({CFG['decisions_link']})."
    parts.append("## Overview\n\n" + overview)
    extra = optional(F_DIR / "_overview.md")
    if extra:
        parts.append(extra)
    for title_text, body in groups():
        rows = "\n".join(render_row(m, t) for m, t in order(items) if m["group"] == title_text)
        parts.append(body.replace(MARKER, rows))
    return "\n\n".join(parts) + "\n"


def generate_feedback() -> str:
    items = feedback_items()
    title, rest = intro_of(FB_DIR, "# Feedback")
    parts = [title + "\n\n" + generated_note(CFG["feedback_dir"]) + ("\n\n" + rest if rest else "")]
    table = ["| ID | Area | Finding | Priority | Status | Related finding |", "| --- | --- | --- | --- | --- | --- |"]
    for m, _ in items:
        table.append(f"| {m['id']} | {m['area']} | {m['summary']} | {m['priority']} | {m['status']} | {m['related']} |")
    parts.append(f"## Overview\n\n{len(items)} items.\n\n" + "\n".join(table))
    template = optional(FB_DIR / "_template.md")
    if template:
        parts.append(template)
    for _, body in items:
        parts.append(body)
    return "\n\n".join(parts) + "\n"


def write_generated() -> None:
    for name, text in (("findings_index", generate_findings()), ("feedback_index", generate_feedback())):
        path = ROOT / CFG[name]
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")


def check_records(directory: Path, keys: tuple, id_re: re.Pattern, errors: list[str], validate) -> None:
    seen: dict = {}
    for p in sorted(directory.glob("*.md")):
        if p.name.startswith("_"):
            continue
        try:
            meta, body = read_record(p)
        except (ValueError, json.JSONDecodeError) as e:
            errors.append(f"{p.name}: unreadable ({e})")
            continue
        missing = [k for k in keys if k not in meta]
        if missing:
            errors.append(f"{p.name}: missing {', '.join(missing)}")
            continue
        if meta["id"] != p.stem or not id_re.match(meta["id"]):
            errors.append(f"{p.name}: id {meta['id']} does not match the file name or the id pattern")
        if meta["id"] in seen:
            errors.append(f"{meta['id']}: duplicate id ({seen[meta['id']]} and {p.name})")
        seen[meta["id"]] = p.name
        validate(meta, body)


def check() -> list[str]:
    errors: list[str] = []
    titles = [t for t, _ in groups()]

    def finding(meta: dict, body: str) -> None:
        if meta["status"] not in STATUSES:
            errors.append(f"{meta['id']}: status '{meta['status']}' is not one of {', '.join(STATUSES)}")
        if meta["severity"] not in SEVERITIES:
            errors.append(f"{meta['id']}: severity '{meta['severity']}' is not one of {', '.join(SEVERITIES)}")
        if meta["group"] not in titles:
            errors.append(f"{meta['id']}: unknown group '{meta['group']}'")
        if not body.strip():
            errors.append(f"{meta['id']}: empty finding text")

    def feedback(meta: dict, body: str) -> None:
        if not body.startswith(f"### {meta['id']} "):
            errors.append(f"{meta['id']}: the body must start with '### {meta['id']} title'")

    check_records(F_DIR, F_KEYS, ID_RE, errors, finding)
    check_records(FB_DIR, FB_KEYS, FB_ID_RE, errors, feedback)
    if errors:
        return errors
    for name, expected in (("findings_index", generate_findings()), ("feedback_index", generate_feedback())):
        path = ROOT / CFG[name]
        if not path.exists() or path.read_text(encoding="utf-8") != expected:
            errors.append(f"{CFG[name]} is not up to date: run {CFG['command']} index")
    return errors


def find(item_id: str, fb: bool = False) -> tuple[Path, dict, str]:
    directory = FB_DIR if fb else F_DIR
    path = directory / f"{item_id}.md"
    if not path.exists():
        sys.exit(f"{item_id}: no such {'feedback item' if fb else 'finding'} ({path})")
    meta, body = read_record(path)
    return path, meta, body


def option(args: list[str], name: str, required: bool = True) -> str | None:
    if name in args:
        i = args.index(name)
        if i + 1 < len(args):
            return args[i + 1]
    if required:
        sys.exit(f"missing {name}")
    return None


def cmd_add(args: list[str]) -> None:
    cmd = CFG["command"]
    if not args or not ID_RE.match(args[0]):
        sys.exit(f"usage: {cmd} add <ID matching {CFG['finding_id_pattern']}> --group <title> --severity <{'|'.join(SEVERITIES[:4])}> --found-by <text> --text-file <file> [--status open|fixed|...] [--note <text>]")
    item_id = args[0]
    path = F_DIR / f"{item_id}.md"
    if path.exists():
        sys.exit(f"{item_id} exists already ({path}); pick the next free id or use 'status'")
    group = option(args, "--group")
    severity = option(args, "--severity")
    status = option(args, "--status", False) or "open"
    note = option(args, "--note", False)
    if group not in [t for t, _ in groups()]:
        sys.exit("unknown group; choose one of: " + "; ".join(t for t, _ in groups()))
    if severity not in SEVERITIES or status not in STATUSES:
        sys.exit(f"severity must be one of {', '.join(SEVERITIES)}; status one of {', '.join(STATUSES)}")
    text_file = Path(option(args, "--text-file"))
    if not text_file.is_file():
        sys.exit(f"--text-file {text_file}: no such file")
    text = text_file.read_text(encoding="utf-8").strip()
    if "\n" in text:
        sys.exit("the finding text must be one line (it becomes a table cell)")
    positions = [m["position"] for m, _ in findings() if m["group"] == group]
    meta = {
        "id": item_id, "group": group, "position": (max(positions) + 1) if positions else 1, "severity": severity,
        "found_by": option(args, "--found-by"), "status": status, "status_note": f": {note}" if note else "",
    }
    write_record(path, meta, F_KEYS, text)
    print(f"added {rel(path)}; run {cmd} index")


def cmd_status(args: list[str], fb: bool) -> None:
    cmd = CFG["command"]
    if len(args) < 2:
        sys.exit(f"usage: {cmd} status <ID> <{'|'.join(STATUSES)}> [note]\n       {cmd} fb status <{CFG['feedback_prefix']}-ID> <status text>")
    path, meta, body = find(args[0], fb)
    if fb:
        meta["status"] = " ".join(args[1:])
        write_record(path, meta, FB_KEYS, body)
    else:
        if args[1] not in STATUSES:
            sys.exit(f"status must be one of {', '.join(STATUSES)}")
        meta["status"] = args[1]
        meta["status_note"] = f": {' '.join(args[2:])}" if len(args) > 2 else ""
        write_record(path, meta, F_KEYS, body)
    print(f"{args[0]} -> {meta['status']}; run {cmd} index")


def cmd_show(args: list[str], fb: bool) -> None:
    if not args:
        sys.exit(f"usage: {CFG['command']} show <ID>")
    _, meta, body = find(args[0], fb)
    if fb:
        print(f"{meta['id']} | {meta['area']} | {meta['priority']} | {meta['status']} | related: {meta['related']}\n")
        print(body)
    else:
        print(render_row(meta, body))


def cmd_list(args: list[str], fb: bool) -> None:
    wanted = option(args, "--status", False)
    if fb:
        for m, _ in feedback_items():
            print(f"{m['id']}\t{m['priority']}\t{m['status']}\t{m['summary']}")
        return
    for m, text in order(findings()):
        if wanted and m["status"] != wanted:
            continue
        print(f"{m['id']}\t{m['severity']}\t{m['status']}\t{text[:110]}")


def split_config(argv: list[str]) -> tuple[str | None, list[str]]:
    if argv and argv[0] == "--config":
        if len(argv) < 2:
            sys.exit("--config needs a file")
        return argv[1], argv[2:]
    return None, argv


def main() -> None:
    config, args = split_config(sys.argv[1:])
    configure(config)
    if not args or args[0] in ("-h", "--help"):
        print(__doc__)
        sys.exit(0 if args else 1)
    fb = args[0] == "fb"
    if fb:
        args = args[1:]
    cmd, rest = (args[0], args[1:]) if args else ("", [])
    if cmd == "add" and not fb:
        cmd_add(rest)
    elif cmd == "status":
        cmd_status(rest, fb)
    elif cmd == "show":
        cmd_show(rest, fb)
    elif cmd == "list":
        cmd_list(rest, fb)
    elif cmd == "counts":
        print(counts_text(counts(findings())))
    elif cmd == "index":
        write_generated()
        print(f"regenerated {CFG['findings_index']} and {CFG['feedback_index']}")
    elif cmd == "check":
        errors = check()
        for e in errors:
            print(f"ERROR {e}", file=sys.stderr)
        if errors:
            sys.exit(1)
        print(f"ok: {len(findings())} findings, {len(feedback_items())} feedback items, generated files up to date")
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
