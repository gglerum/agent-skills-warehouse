#!/usr/bin/env python3
"""Decisions as one file per decision; the overview document is generated from them.

Usage: python3 decisions.py [--config FILE] <command> [arguments]

Records (all paths come from the configuration, relative to the configuration file or the working directory):

  <records_dir>/<PREFIX>-001.md     one current decision (front matter + the decision text)
  <records_dir>/archive/            superseded decisions (moved there by `supersede`; never looked up by accident)
  <records_dir>/_acknowledged.md    tracker comments that were read and hold no decision (`ack`)
  <records_dir>/_intro.md           text above the generated tables of the overview (first line is its title)

The record is the single source of truth. A decision that belongs to a tracker issue can be listed there, because
readers often use the tracker and not the repository: `mirror` keeps one section in the issue body with a line and a
direct link to the file per decision (the text is not copied). That section is never edited by hand. Everything else
(stories, wireframes, skills, other docs) names the id and does not repeat the text.

Generated, committed, never edited by hand: the overview file (`index_file`).
Commands: add, status, supersede, show, list, for, mirror, strays, ack, index, check.
DECISIONS_GH=<command> replaces `gh` (used by the tests). Python 3.10+ standard library only.
"""

from __future__ import annotations

import json
import os
import re
import subprocess
import sys
from pathlib import Path

DEFAULTS = {
    "records_dir": "docs/decisions",
    "index_file": "docs/decisions.md",
    "id_prefix": "DEC",
    "id_digits": 3,
    "tracker_repo": None,  # "owner/repository"; enables `mirror` and `strays`
    "tracker_host": "https://github.com",
    "default_branch": "main",
    "reviewer_login": None,  # comments of this login that are not recorded or acknowledged are strays
    "decision_marker": "**Decision",  # a comment starting with this text looks like a decision
    "section_title": "Decisions",
    "reference_paths": ["docs", "README.md"],  # where ids may be referenced; every id found must exist
    "history_files": [],  # logs of what happened; they may still name superseded decisions
    "command": "python3 decisions.py",  # how the notes below name this tool
}

STATUSES = ("decided", "proposed", "open", "superseded")
LABELS = {"decided": "Decided", "proposed": "Proposed (awaiting approval)", "open": "Open", "superseded": "Superseded"}
KEYS = ("id", "title", "status", "decided_on", "decided_by", "issue", "stories", "related", "supersedes", "superseded_by", "sources", "mirror")

CFG: dict = {}
ROOT = Path.cwd()
D_DIR = ARCHIVE = REVIEWED = INDEX = Path()
ID_RE = REF_RE = re.compile("")
SECTION_START = "<!-- decisions -->"
SECTION_END = "<!-- /decisions -->"


def configure(config_path: str | None) -> None:
    global CFG, ROOT, D_DIR, ARCHIVE, REVIEWED, INDEX, ID_RE, REF_RE
    CFG = dict(DEFAULTS)
    ROOT = Path.cwd()
    if config_path:
        path = Path(config_path).resolve()
        CFG.update(json.loads(path.read_text(encoding="utf-8")))
        ROOT = path.parent
    ROOT = Path(os.environ.get("DECISIONS_ROOT") or ROOT)
    D_DIR = ROOT / CFG["records_dir"]
    ARCHIVE = D_DIR / "archive"
    REVIEWED = D_DIR / "_acknowledged.md"
    INDEX = ROOT / CFG["index_file"]
    prefix, digits = re.escape(CFG["id_prefix"]), int(CFG["id_digits"])
    ID_RE = re.compile(rf"^{prefix}-[0-9]{{{digits}}}$")
    REF_RE = re.compile(rf"\b{prefix}-[0-9]{{{digits}}}\b")


def rel(path: Path) -> str:
    try:
        return str(path.relative_to(ROOT))
    except ValueError:
        return str(path)


def generated_note() -> str:
    cmd = CFG["command"]
    return (
        f"> Generated by `{cmd} index` from the files in `{CFG['records_dir']}/`. Do not edit this file: change a "
        f"decision with `{cmd}` (or edit its file) and run `{cmd} index`. On a merge conflict in this "
        f"file, run `{cmd} index` and add the result."
    )


def tracker_url() -> str:
    return f"{CFG['tracker_host']}/{CFG['tracker_repo']}"


def read_record(path: Path) -> tuple[dict, str]:
    text = path.read_text(encoding="utf-8")
    m = re.match(r"---\n(.*?)\n---\n?(.*)\Z", text, re.S)
    if not m:
        raise ValueError(f"{path}: no front matter")
    meta = {}
    for line in m.group(1).split("\n"):
        key, _, value = line.partition(": ")
        meta[key] = json.loads(value)
    return meta, m.group(2).strip("\n")


def write_record(path: Path, meta: dict, body: str) -> None:
    lines = [f"{k}: {json.dumps(meta[k], ensure_ascii=False)}" for k in KEYS]
    path.write_text("---\n" + "\n".join(lines) + "\n---\n" + body.strip("\n") + "\n", encoding="utf-8")


def record_paths() -> list[Path]:
    pattern = f"{CFG['id_prefix']}-*.md"
    return sorted(D_DIR.glob(pattern)) + sorted(ARCHIVE.glob(pattern))


def decisions(include_superseded: bool = True) -> list[tuple[dict, str]]:
    items = [read_record(p) for p in record_paths()]
    return items if include_superseded else [it for it in items if it[0]["status"] != "superseded"]


def record_path(decision_id: str) -> Path:
    for directory in (D_DIR, ARCHIVE):
        if (directory / f"{decision_id}.md").exists():
            return directory / f"{decision_id}.md"
    return D_DIR / f"{decision_id}.md"


def link_issue(n: int) -> str:
    return f"[#{n}]({tracker_url()}/issues/{n})" if CFG["tracker_repo"] else f"#{n}"


def row(meta: dict) -> str:
    where = ", ".join(link_issue(n) for n in ([meta["issue"]] if meta["issue"] else []) + list(meta["stories"])) or "-"
    when = meta["decided_on"] or "-"
    by = meta["decided_by"] or "-"
    note = f" (superseded by {meta['superseded_by']})" if meta["superseded_by"] else ""
    target = os.path.relpath(D_DIR / ("archive" if meta["status"] == "superseded" else "") / f"{meta['id']}.md", INDEX.parent)
    return f"| [{meta['id']}]({target}) | {meta['title']}{note} | {when} | {by} | {where} |"


def generate_index() -> str:
    items = decisions()
    intro_path = D_DIR / "_intro.md"
    intro = intro_path.read_text(encoding="utf-8").strip("\n") if intro_path.exists() else "# Decisions"
    title, _, rest = intro.partition("\n")
    parts = [title + "\n\n" + generated_note() + ("\n\n" + rest.strip("\n") if rest.strip() else "")]
    counts = {s: sum(1 for m, _ in items if m["status"] == s) for s in STATUSES}
    parts.append(
        f"{len(items)} decisions: {counts['decided']} decided, {counts['proposed']} proposed, {counts['open']} open, "
        f"{counts['superseded']} superseded."
    )
    header = "| ID | Decision | Date | By | Issue / stories |\n| --- | --- | --- | --- | --- |"
    for status, heading in (("open", "Open: a person must decide"), ("proposed", "Proposed: awaiting approval"), ("decided", "Decided"), ("superseded", "Superseded")):
        rows = [row(m) for m, _ in items if m["status"] == status]
        if rows:
            parts.append(f"## {heading}\n\n{header}\n" + "\n".join(rows))
    return "\n\n".join(parts) + "\n"


def write_generated() -> None:
    INDEX.parent.mkdir(parents=True, exist_ok=True)
    INDEX.write_text(generate_index(), encoding="utf-8")


def references() -> dict[str, list[str]]:
    """Every id mentioned outside the records, with the files that mention it."""
    found: dict[str, list[str]] = {}
    for item in CFG["reference_paths"]:
        base = ROOT / item
        if not base.exists():
            continue
        files = [base] if base.is_file() else sorted(p for p in base.rglob("*") if p.is_file() and p.suffix in (".md", ".html"))
        for path in files:
            if D_DIR in path.parents or path == INDEX:
                continue
            for ref in REF_RE.findall(path.read_text(encoding="utf-8", errors="ignore")):
                found.setdefault(ref, []).append(rel(path))
    return found


def check() -> list[str]:
    errors = []
    seen = {}
    records = {}
    cmd = CFG["command"]
    for p in record_paths():
        try:
            meta, body = read_record(p)
        except (ValueError, json.JSONDecodeError) as e:
            errors.append(f"{p.name}: unreadable ({e})")
            continue
        missing = [k for k in KEYS if k not in meta]
        if missing:
            errors.append(f"{p.name}: missing {', '.join(missing)}")
            continue
        archived = p.parent == ARCHIVE
        if archived and meta["status"] != "superseded":
            errors.append(f"{meta['id']}: is in archive/ but not superseded")
        if not archived and meta["status"] == "superseded":
            errors.append(f"{meta['id']}: is superseded but not in archive/: run {cmd} supersede")
        if not ID_RE.match(meta["id"]) or meta["id"] != p.stem:
            errors.append(f"{p.name}: id {meta['id']} does not match the file name ({CFG['id_prefix']}-nnn)")
        if meta["id"] in seen:
            errors.append(f"{meta['id']}: duplicate id")
        seen[meta["id"]] = p.name
        records[meta["id"]] = meta
        if meta["status"] not in STATUSES:
            errors.append(f"{meta['id']}: status '{meta['status']}' is not one of {', '.join(STATUSES)}")
        if not body.strip():
            errors.append(f"{meta['id']}: empty decision text")
        if not meta["title"].strip():
            errors.append(f"{meta['id']}: empty title")
        if meta["status"] in ("decided", "superseded"):
            if not meta["decided_on"] or not meta["decided_by"]:
                errors.append(f"{meta['id']}: a decided decision needs decided_on and decided_by")
            if not meta["issue"] and not meta["sources"]:
                errors.append(f"{meta['id']}: a decided decision needs an issue or a source (where was it decided?)")
        if meta["issue"] and CFG["tracker_repo"] and not meta["mirror"]:
            errors.append(f"{meta['id']}: issue #{meta['issue']} but not mirrored into its body: run {cmd} mirror {meta['id']}")
        if (meta["status"] == "superseded") != bool(meta["superseded_by"]):
            errors.append(f"{meta['id']}: status 'superseded' and superseded_by must go together")
    for meta in records.values():
        for other in list(meta["supersedes"]) + ([meta["superseded_by"]] if meta["superseded_by"] else []):
            if other not in records:
                errors.append(f"{meta['id']}: refers to unknown decision {other}")
        for old in meta["supersedes"]:
            if old in records and records[old]["superseded_by"] != meta["id"]:
                errors.append(f"{meta['id']}: supersedes {old}, but {old} does not say superseded_by {meta['id']}")
    for ref, files in sorted(references().items()):
        if ref not in records:
            errors.append(f"{ref} is referenced in {', '.join(sorted(set(files)))} but has no record in {CFG['records_dir']}/")
        elif records[ref]["status"] == "superseded":
            live = sorted({f for f in files if f not in CFG["history_files"]})
            if live:
                errors.append(f"{ref} is superseded by {records[ref]['superseded_by']} but still referenced in {', '.join(live)}: point to {records[ref]['superseded_by']}")
    if errors:
        return errors
    if not INDEX.exists() or INDEX.read_text(encoding="utf-8") != generate_index():
        errors.append(f"{CFG['index_file']} is not up to date: run {cmd} index")
    return errors


def find(decision_id: str) -> tuple[Path, dict, str]:
    path = record_path(decision_id)
    if not path.exists():
        sys.exit(f"{decision_id}: no such decision ({path})")
    meta, body = read_record(path)
    return path, meta, body


def option(args: list[str], name: str, required: bool = True) -> str | None:
    if name in args:
        i = args.index(name)
        if i + 1 < len(args):
            return args[i + 1]
    if required:
        sys.exit(f"missing {name}")
    return None


def numbers(value: str | None) -> list[int]:
    return [int(n) for n in re.findall(r"\d+", value or "")]


def words(value: str | None) -> list[str]:
    return [w for w in re.split(r"[ ,]+", value or "") if w]


def next_id() -> str:
    prefix = CFG["id_prefix"]
    nums = [int(m["id"].rsplit("-", 1)[1]) for m, _ in decisions()]  # includes archived ids: an id is never reused
    return f"{prefix}-{(max(nums) + 1) if nums else 1:0{int(CFG['id_digits'])}d}"


def cmd_add(args: list[str]) -> None:
    cmd = CFG["command"]
    usage = (
        f"usage: {cmd} add --title <text> --status <decided|proposed|open> --text-file <file> [--on YYYY-MM-DD] [--by <who>]\n"
        "       [--issue <decision issue number>] [--stories '#51 #52'] [--related 'F10 FB-005'] [--sources '<url> <url>'] [--id <ID>]\n"
        f"       With --issue, run `{cmd} mirror <ID>` afterwards (or give --mirror <issue url>)."
    )
    if "--title" not in args:
        sys.exit(usage)
    status = option(args, "--status")
    if status not in ("decided", "proposed", "open"):
        sys.exit("status must be decided, proposed or open (use 'supersede' to replace a decision)")
    text_file = Path(option(args, "--text-file"))
    if not text_file.is_file():
        sys.exit(f"--text-file {text_file}: no such file")
    decision_id = option(args, "--id", False) or next_id()
    if not ID_RE.match(decision_id):
        sys.exit(f"{decision_id}: an id looks like {CFG['id_prefix']}-{'0' * (int(CFG['id_digits']) - 1)}1")
    path = D_DIR / f"{decision_id}.md"
    if record_path(decision_id).exists():
        sys.exit(f"{decision_id} exists already ({record_path(decision_id)})")
    issue = numbers(option(args, "--issue", False))
    meta = {
        "id": decision_id, "title": option(args, "--title"), "status": status,
        "decided_on": option(args, "--on", False) or "", "decided_by": option(args, "--by", False) or "",
        "issue": issue[0] if issue else None, "stories": numbers(option(args, "--stories", False)),
        "related": words(option(args, "--related", False)), "supersedes": [], "superseded_by": None,
        "sources": words(option(args, "--sources", False)), "mirror": option(args, "--mirror", False),
    }
    D_DIR.mkdir(parents=True, exist_ok=True)
    write_record(path, meta, text_file.read_text(encoding="utf-8"))
    print(f"added {rel(path)}; run `{cmd} mirror {decision_id}` (if it has an issue), then index")


def cmd_status(args: list[str]) -> None:
    cmd = CFG["command"]
    if len(args) < 2 or args[1] not in ("decided", "proposed", "open"):
        sys.exit(f"usage: {cmd} status <ID> <decided|proposed|open> [--on YYYY-MM-DD] [--by <who>]")
    path, meta, body = find(args[0])
    if meta["status"] == "superseded":
        sys.exit(f"{args[0]} is superseded by {meta['superseded_by']} and archived; change {meta['superseded_by']} instead")
    meta["status"] = args[1]
    meta["decided_on"] = option(args, "--on", False) or meta["decided_on"]
    meta["decided_by"] = option(args, "--by", False) or meta["decided_by"]
    write_record(path, meta, body)
    print(f"{args[0]} -> {args[1]}; run `{cmd} mirror {args[0]}` (to update the issue bodies) and index")


def cmd_supersede(args: list[str]) -> None:
    cmd = CFG["command"]
    if len(args) != 2:
        sys.exit(f"usage: {cmd} supersede <old ID> <new ID>")
    old_path, old, old_body = find(args[0])
    new_path, new, new_body = find(args[1])
    if old["status"] == "superseded":
        sys.exit(f"{old['id']} is superseded already (by {old['superseded_by']})")
    old["status"], old["superseded_by"] = "superseded", new["id"]
    new["supersedes"] = sorted(set(new["supersedes"]) | {old["id"]})
    ARCHIVE.mkdir(parents=True, exist_ok=True)
    write_record(ARCHIVE / old_path.name, old, old_body)
    if old_path.parent != ARCHIVE:
        old_path.unlink()
    write_record(new_path, new, new_body)
    print(f"{old['id']} is superseded by {new['id']} and moved to {CFG['records_dir']}/archive/; run `{cmd} mirror` for both, then index.\n"
          f"Point every issue and doc that names {old['id']} to {new['id']} (`check` fails on a doc that still names it; `strays` lists open issues).")


def cmd_show(args: list[str]) -> None:
    if not args:
        sys.exit(f"usage: {CFG['command']} show <ID>")
    _, meta, body = find(args[0])
    if meta["status"] == "superseded":
        print(f"!!! {meta['id']} IS SUPERSEDED (archived): do not use it. Use {meta['superseded_by']}: {CFG['command']} show {meta['superseded_by']}\n")
    print(f"{meta['id']} | {meta['title']} | {LABELS[meta['status']]} | {meta['decided_on'] or '-'} | {meta['decided_by'] or '-'}")
    where = [f"#{n}" for n in ([meta["issue"]] if meta["issue"] else []) + list(meta["stories"])]
    print(f"issue/stories: {' '.join(where) or '-'} | related: {' '.join(meta['related']) or '-'}")
    if meta["supersedes"] or meta["superseded_by"]:
        print(f"supersedes: {' '.join(meta['supersedes']) or '-'} | superseded by: {meta['superseded_by'] or '-'}")
    print(f"tracker: {meta['mirror'] or '-'}\n")
    print(body)


def cmd_list(args: list[str]) -> None:
    wanted = option(args, "--status", False)
    for m, _ in decisions(include_superseded="--all" in args or wanted == "superseded"):
        if wanted and m["status"] != wanted:
            continue
        print(f"{m['id']}\t{m['status']}\t{m['decided_on'] or '-'}\t{m['title']}")


def cmd_for(args: list[str]) -> None:
    """The decisions that apply to an issue (its own and the ones naming it as a story) or to a related finding id."""
    if not args:
        sys.exit(f"usage: {CFG['command']} for <issue number | related id> [more]")
    for key in args:
        number = int(key.lstrip("#")) if key.lstrip("#").isdigit() else None
        hits = [(m, b) for m, b in decisions(include_superseded=False) if (number is not None and (m["issue"] == number or number in m["stories"])) or key in m["related"]]
        print(f"--- decisions for {key}: {', '.join(m['id'] for m, _ in hits) or 'none'}")
        for m, b in hits:
            print(f"\n{m['id']} [{m['status']}] {m['title']}\n{b}")


def gh(*args: str, stdin: str | None = None) -> str:
    command = (os.environ.get("DECISIONS_GH") or "gh").split()
    result = subprocess.run([*command, *args], input=stdin, capture_output=True, text=True)
    if result.returncode != 0:
        sys.exit(f"gh {' '.join(args[:2])} failed: {result.stderr.strip()}")
    return result.stdout.strip()


def need_tracker() -> None:
    if not CFG["tracker_repo"]:
        sys.exit("this command needs `tracker_repo` (owner/repository) in the configuration")


def decision_link(meta: dict) -> str:
    folder = f"{CFG['records_dir']}/archive" if meta["status"] == "superseded" else CFG["records_dir"]
    return f"{tracker_url()}/blob/{CFG['default_branch']}/{folder}/{meta['id']}.md"


def decision_lines(issue: int) -> str:
    """Every current decision of an issue (its own decision issue or one of its stories) as a line with a direct link to its file.
    A superseded decision is left out: the issue must not name it any more (the archive keeps the history)."""
    lines = []
    for meta, _ in decisions(include_superseded=False):
        if meta["issue"] != issue and issue not in meta["stories"]:
            continue
        lines.append(f"- **{meta['id']}**: {meta['title']} · {LABELS[meta['status']]} · [read the decision]({decision_link(meta)})")
    return "\n".join(lines)


def with_decisions_section(body: str, lines: str) -> str:
    """The body with its decisions section replaced by the generated lines (between markers, so a rerun only touches those)."""
    title = CFG["section_title"]
    block = f"## {title}\n{SECTION_START}\n{lines}\n{SECTION_END}"
    if SECTION_START in body and SECTION_END in body:
        return re.sub(re.escape(SECTION_START) + r".*?" + re.escape(SECTION_END), lambda _: f"{SECTION_START}\n{lines}\n{SECTION_END}", body, flags=re.S)
    old = re.search(rf"^## {re.escape(title)}\n.*?(?=^## |\Z)", body, flags=re.S | re.M)
    if old:
        rest = body[old.end():].lstrip("\n")
        return body[:old.start()] + block + "\n" + ("\n" + rest if rest else "")
    return body.rstrip("\n") + "\n\n" + block + "\n"


def cmd_mirror(args: list[str]) -> None:
    """Write the decisions of the issue (and of its stories) as a section with links into the issue body, and point every decision at it."""
    need_tracker()
    cmd = CFG["command"]
    if not args:
        sys.exit(f"usage: {cmd} mirror <ID> [--dry-run]")
    _, meta, _ = find(args[0])
    targets = sorted({n for n in [meta["issue"], *meta["stories"]] if n})
    if not targets:
        sys.exit(f"{meta['id']} has no issue and no stories; give it one with the front matter field 'issue' or 'stories' first")
    for issue in targets:
        lines = decision_lines(issue)
        if "--dry-run" in args:
            print(f"--- #{issue}\n{lines}")
            continue
        body = gh("issue", "view", str(issue), "-R", CFG["tracker_repo"], "--json", "body", "--jq", ".body")
        new = with_decisions_section(body, lines)
        if new.strip() != body.strip():
            gh("issue", "edit", str(issue), "-R", CFG["tracker_repo"], "--body-file", "-", stdin=new)
            print(f"updated the body of #{issue}")
    if "--dry-run" in args:
        return
    if not meta["issue"]:
        print(f"run {cmd} index")
        return
    url = f"{tracker_url()}/issues/{meta['issue']}"
    for other, other_body in decisions():
        if other["issue"] == meta["issue"] and other["mirror"] != url:
            other["mirror"] = url
            write_record(record_path(other["id"]), other, other_body)
    print(f"run {cmd} index")


def acked() -> set[str]:
    if not REVIEWED.exists():
        return set()
    return {line.split(" | ")[0].strip("- ").strip() for line in REVIEWED.read_text(encoding="utf-8").split("\n") if line.startswith("- http")}


def cmd_ack(args: list[str]) -> None:
    cmd = CFG["command"]
    if len(args) < 2 or not args[0].startswith("http"):
        sys.exit(f"usage: {cmd} ack <comment url> <why it holds no decision>")
    REVIEWED.parent.mkdir(parents=True, exist_ok=True)
    with REVIEWED.open("a", encoding="utf-8") as f:
        if REVIEWED.stat().st_size == 0:
            f.write(f"# Read, no decision\n\nTracker comments that were read and contain no decision (`{cmd} ack`). `{cmd} strays` skips them.\n\n")
        f.write(f"- {args[0]} | {' '.join(args[1:])}\n")
    print(f"noted {args[0]}")


def cmd_strays(_: list[str]) -> None:
    """What in the tracker is not (yet) a record: decision-looking comments, comments of the reviewer that are not
    recorded or acknowledged, and open issues that still name a superseded decision."""
    need_tracker()
    cmd = CFG["command"]
    known = acked()
    for m, _ in decisions():
        known.update(m["sources"])
        if m["mirror"]:
            known.add(m["mirror"])
    login = CFG["reviewer_login"] or ""
    marker = CFG["decision_marker"]
    condition = f'(.user.login=="{login}") or ' if login else ""
    query = f'.[]|select({condition}(.body|startswith("{marker}"))) | select(.body|startswith("<!-- decision")|not) | [.html_url, .user.login, .body[:90]] | @tsv'
    out = gh("api", f"repos/{CFG['tracker_repo']}/issues/comments", "--paginate", "--jq", query)
    problems = []
    for line in [line for line in out.split("\n") if line]:
        url, author, text = (line.split("\t") + ["", ""])[:3]
        if url in known:
            continue
        what = "comment of the reviewer, not recorded" if login and author == login else "looks like a decision, belongs to no record"
        problems.append(f"{url}\t{what}\t{text}")
    stale = {m["id"]: m["superseded_by"] for m, _ in decisions() if m["status"] == "superseded"}
    if stale:
        issues = gh("issue", "list", "-R", CFG["tracker_repo"], "--state", "open", "--limit", "200", "--json", "number,body", "--jq", r'.[]|[.number,(.body|gsub("\n";" "))]|@tsv')
        for line in [line for line in issues.split("\n") if line]:
            number, _, body = line.partition("\t")
            for old, new in stale.items():
                if old in body:
                    problems.append(f"{tracker_url()}/issues/{number}\tnames {old}, which is superseded by {new}\t")
    for p in problems:
        print(p)
    if problems:
        sys.exit(f"{len(problems)} item(s) to handle: record the decision (add/status/supersede), or `ack` a comment that holds none, or fix the issue text")
    print("ok: nothing in the tracker is waiting to become a decision record")


def split_config(argv: list[str]) -> tuple[str | None, list[str]]:
    if argv and argv[0] == "--config":
        if len(argv) < 2:
            sys.exit("--config needs a file")
        return argv[1], argv[2:]
    return None, argv


def main() -> None:
    config, args = split_config(sys.argv[1:])
    configure(config)
    if not args or args[0] in ("-h", "--help"):
        print(__doc__)
        sys.exit(0 if args else 1)
    cmd, rest = args[0], args[1:]
    commands = {"add": cmd_add, "status": cmd_status, "supersede": cmd_supersede, "show": cmd_show, "list": cmd_list,
                "for": cmd_for, "mirror": cmd_mirror, "strays": cmd_strays, "ack": cmd_ack}
    if cmd in commands:
        commands[cmd](rest)
    elif cmd == "index":
        write_generated()
        print(f"regenerated {CFG['index_file']}")
    elif cmd == "check":
        errors = check()
        for e in errors:
            print(f"ERROR {e}", file=sys.stderr)
        if errors:
            sys.exit(1)
        print(f"ok: {len(decisions())} decisions, generated file up to date")
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
